const dicts: Record<string, Dict> = { en, es, 'zh-CN': zh, 'zh-TW': zh, ar };

export function historyText(lang: string, key: HistoryKey, n?: number): string {
  const s = (dicts[lang] ?? en)[key];
  return n === undefined ? s : s.replace('{n}', String(n));
}
